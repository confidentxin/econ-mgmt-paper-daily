export interface JournalClassification {
  tier: "T1" | "T1_5";
  selectionClass: "abs3" | "adjacent" | null;
  absTag: "ABS 4*" | "ABS 4" | "ABS 3" | null;
}

export function classifyJournal(journal: { sourceId: string; lists: readonly string[] }): JournalClassification {
  const isTopList = journal.lists.includes("UTD24") || journal.lists.includes("FT50");
  const is4Star = ABS_4_STAR_SOURCE_IDS.has(journal.sourceId);
  const is4 = ABS_4_SOURCE_IDS.has(journal.sourceId);
  const isAdjacent = ADJACENT_SOURCE_IDS.has(journal.sourceId);

  const tier: "T1" | "T1_5" = isTopList || is4Star ? "T1" : "T1_5";
  const absTag: JournalClassification["absTag"] = !journal.lists.includes("ABS")
    ? null
    : is4Star || journal.lists.includes("UTD24")
      ? "ABS 4*"
      : is4 || journal.lists.includes("FT50")
        ? "ABS 4"
        : "ABS 3";

  const selectionClass: JournalClassification["selectionClass"] = isAdjacent
    ? "adjacent"
    : tier === "T1_5" && !is4
      ? "abs3"
      : null;

  return { tier, selectionClass, absTag };
}
